// Scope and checkbox names belong to the integrator export. Until scopes are exported, publish
// only an unavailable notice, never rows that turn missing metadata into "no permission needed".
function permissionsPage() {
  if (!reference.spec) return { page: null, withheld: reference.withheld, missingLabels: [] };
  const spec = JSON.parse(reference.spec);
  const methods = new Set(['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']);
  const operations = [];
  for (const [route, item] of Object.entries(spec.paths ?? {})) {
    if (item.$ref) throw new Error(`PERMISSIONS_PATH_REFERENCE_UNRESOLVED ${route}`);
    for (const [method, operation] of Object.entries(item)) {
      if (!methods.has(method)) continue;
      const security = operation.security ?? spec.security ?? [];
      if (!Array.isArray(security) || security.some((requirement) => !requirement ||
          typeof requirement !== 'object' || Array.isArray(requirement) ||
          Object.values(requirement).some((scopes) => !Array.isArray(scopes) ||
            scopes.some((scope) => typeof scope !== 'string' || !scope.trim())))) {
        throw new Error(`PERMISSIONS_SECURITY_INVALID ${method.toUpperCase()} ${route}`);
      }
      operations.push({ route, method: method.toUpperCase(), security, tag: Array.isArray(operation.tags) && typeof operation.tags[0] === 'string' ? operation.tags[0] : 'Other' });
    }
  }
  const hasScopes = operations.some(({ security }) => security.some((requirement) =>
    Object.values(requirement).some((scopes) => scopes.length)));
  const heading = [
    '---',
    'title: "Permissions"',
    'description: "API-key scopes and the app permissions that grant them, for each API operation."',
    '---',
    '',
    '{/* Generated by scripts/sync-contract.mjs from tetrafi-rfq docs/api/integrator/openapi.json. Edit the source, then run npm run sync. */}',
    '',
  ];
  if (!hasScopes) return { page: [
    ...heading,
    'The permission matrix is not yet available because the API specification has not exported operation scopes. This does not mean that operations need no permissions. See [Authentication permissions](/authentication#permissions) for the app permissions you can select.',
    '',
  ].join('\n'), withheld: null, missingLabels: [], scopesNotExported: true, operations,
    access: () => ({ scopes: 'Not exported yet', permissions: 'Not exported yet' }), code: (value) => `\`${value.replace(/\|/g, '\\|')}\`` };

  const labels = spec.components?.securitySchemes?.api_key?.['x-tetrafi-scopes'];
  const missingLabels = new Set();
  const cell = (value) => value.replace(/&/g, '&amp;').replace(/\|/g, '&#124;')
    .replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;')
    .replace(/`/g, '&#96;').replace(/\r?\n/g, '<br />');
  // Code spans are literal in MDX: only a pipe, which would split the table cell, is escaped.
  const code = (value) => `\`${value.replace(/\|/g, '\\|')}\``;
  const permission = (scope) => {
    const label = labels && Object.hasOwn(labels, scope) ? labels[scope]?.label : undefined;
    if (typeof label === 'string' && label.trim()) return cell(label);
    missingLabels.add(scope);
    return `SCOPE_LABEL_MISSING (${cell(scope)})`;
  };
  const access = ({ security }) => {
    const keyRequirements = security.filter((requirement) => Object.hasOwn(requirement, 'api_key'));
    let scopes;
    let permissions;
    if (keyRequirements.length) {
      scopes = keyRequirements.map(({ api_key }) => api_key.length ?
        api_key.map(code).join('<br />') : 'None').join(' or ');
      permissions = keyRequirements.map(({ api_key }) => api_key.length ?
        api_key.map(permission).join('<br />') : 'None').join(' or ');
    } else {
      scopes = !security.length || security.some((requirement) => !Object.keys(requirement).length) ?
        'No API key required' : 'Session only';
      permissions = 'Not applicable';
    }
    return { scopes, permissions };
  };
  const row = (op) => {
    const { scopes, permissions } = access(op);
    return `| ${endpointName(op.method, op.route)}<br />${op.method} ${code(op.route)} | ${scopes} | ${permissions} |`;
  };
  // Operations are grouped by their tag, in the spec's tag order, so each section matches the API reference.
  const byRoute = (a, b) => a.route < b.route ? -1 : a.route > b.route ? 1 : a.method < b.method ? -1 : a.method > b.method ? 1 : 0;
  const tagOrder = (spec.tags ?? []).map((tag) => tag.name);
  const tagDescription = new Map((spec.tags ?? []).map((tag) => [tag.name, typeof tag.description === 'string' ? tag.description.trim() : '']));
  const tags = [...new Set(operations.map((op) => op.tag))]
    .sort((a, b) => (tagOrder.includes(a) ? tagOrder.indexOf(a) : 1e3) - (tagOrder.includes(b) ? tagOrder.indexOf(b) : 1e3) || (a < b ? -1 : 1));
  const usedScopes = [...new Set(operations.flatMap(({ security }) => security.flatMap((r) => r.api_key ?? [])))].sort();
  // Every published scope, in the spec's order, then any used scope it does not describe.
  const listedScopes = [...new Set([...(labels && typeof labels === 'object' ? Object.keys(labels) : []), ...usedScopes])];
  const described = (scope) => {
    const text = labels && Object.hasOwn(labels, scope) ? labels[scope]?.description : undefined;
    return typeof text === 'string' && text.trim() ? cell(text) : '';
  };
  return { page: [
    ...heading,
    'Each API operation below lists the API-key scopes it needs. A key names its scopes when you create it ([Authentication](/authentication#permissions)); each scope is `<resource>_read` or `<resource>_write`.',
    '',
    '| Entry | Meaning |',
    '| :--- | :--- |',
    '| Two scopes in one cell | The key needs both. |',
    '| Scopes joined by “or” | Either set is enough. |',
    '| **None** | Any valid key may call it; it still needs authentication. |',
    '| **Session only** | Signed-in app users only; an API key is refused. |',
    '| **No API key required** | Called without an API key; the request carries its own credentials. |',
    '',
    ...(missingLabels.size ? ['<Warning>', 'Some scopes have no exported label. Entries marked `SCOPE_LABEL_MISSING` are incomplete; do not infer what a scope allows from its name.', '</Warning>', ''] : []),
    '## Scopes',
    '',
    '| Scope | Label | What it allows |',
    '| :--- | :--- | :--- |',
    ...listedScopes.map((scope) => `| ${code(scope)} | ${permission(scope)} | ${described(scope)} |`),
    '',
    '## Operations',
    '',
    'Open an area to see what each of its operations needs.',
    '',
    '<AccordionGroup>',
    ...tags.flatMap((tag) => [
      `<Accordion title="${cell(tag.charAt(0).toUpperCase() + tag.slice(1).replace(/-/g, " "))}">`,
      '',
      ...(tagDescription.get(tag) ? [cell(tagDescription.get(tag)), ''] : []),
      '| Operation | API-key scopes | Scope label |',
      '| :--- | :--- | :--- |',
      ...operations.filter((op) => op.tag === tag).sort(byRoute).map(row),
      '',
      '</Accordion>',
    ]),
    '</AccordionGroup>',
    '',
  ].join('\n'), withheld: null, missingLabels: [...missingLabels].sort(), operations, access, code };
}
