#!/usr/bin/env node
// The public contract pages come from the RFQ repository's committed contract files, never from a hand copy:
//   - tetrafi-rfq/docs/api/COMPATIBILITY.md         → compatibility.mdx
//   - tetrafi-rfq/docs/api/integrator/openapi.json  → api-reference/openapi.json (when it exists), reference/permissions.mdx
//   - tetrafi-rfq/docs/api/integrator/error-codes.json → reference/error-codes.mdx
//   - tetrafi-rfq/docs/api/openapi.json, its x-tetrafi-webhook-event-catalogue → reference/webhook-events.mdx
// TETRAFI_RFQ_API_DOCS overrides the source directory.
//
//   node scripts/sync-contract.mjs           write
//   node scripts/sync-contract.mjs --check   exit 1 on drift (CONTRACT_DRIFT <file>)
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { allowedInternalNames, rulesFor, scanText } from './leak-rules.mjs';

const root = path.resolve(import.meta.dirname, '..');
const source = process.env.TETRAFI_RFQ_API_DOCS ?? path.join(root, '..', 'tetrafi-rfq', 'docs', 'api');
const check = process.argv.includes('--check');

// Contract sources are read from tetrafi-rfq's committed HEAD, never its working tree: a peer's
// uncommitted edit there must not reach the public site. With TETRAFI_RFQ_API_DOCS set (tests,
// scratch copies), the files are read as they are. A file HEAD does not have reads as unpublished;
// any other failed read throws rather than passing for an empty contract.
const rfqRoot = path.join(root, '..', 'tetrafi-rfq');
const fromHead = !process.env.TETRAFI_RFQ_API_DOCS && existsSync(path.join(rfqRoot, '.git'));
function sourceText(relative) {
  if (!fromHead) {
    const file = path.join(source, relative);
    return existsSync(file) ? readFileSync(file, 'utf8') : null;
  }
  try {
    return execFileSync('git', ['-C', rfqRoot, 'show', `HEAD:docs/api/${relative}`],
      { encoding: 'utf8', maxBuffer: 512 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (error) {
    if (/does not exist in|exists on disk, but not in/.test(String(error.stderr ?? ''))) return null;
    throw new Error(`CONTRACT_SOURCE_UNREADABLE docs/api/${relative} at tetrafi-rfq HEAD`);
  }
}

function compatibilityPage() {
  const from = path.join(source, 'COMPATIBILITY.md');
  const text = sourceText('COMPATIBILITY.md');
  if (text === null) throw new Error(`missing contract source ${from}`);
  const lines = text.split('\n');
  if (!lines[0].startsWith('# ')) throw new Error(`${from}: expected a level-1 heading on line 1`);
  const body = lines.slice(1).join('\n').replace(/^\n+/, '')
    // Links that point inside the RFQ repository become site links.
    // The reference section exists only once the integrator spec is published.
    .replace(/\[`?integrator\/openapi\.json`?\]\(integrator\/openapi\.json\)/g, reference.spec ? '[API reference](/reference/introduction)' : '[API overview](/overview)')
    .replace(/\]\(CHANGELOG\.md\)/g, '](/changelog)');
  const unmapped = body.match(/\]\((?!https?:|\/|#)[^)]+\)/g);
  if (unmapped) throw new Error(`${from}: relative links with no site page: ${unmapped.join(', ')}`);
  return [
    '---',
    'title: "Compatibility policy"',
    'description: "What can change in the API after launch, what never changes without notice, and how your client stays compatible."',
    '---',
    '',
    '{/* Generated by scripts/sync-contract.mjs from tetrafi-rfq docs/api/COMPATIBILITY.md. Edit the source, then run npm run sync. */}',
    '',
    body.trimEnd(),
    '',
  ].join('\n');
}

// The reference is published only when the spec passes the same leak rules as every page; until
// then it is withheld (never partly scrubbed here: the generator owns its text).
function referenceSpec() {
  const from = path.join(source, 'integrator', 'openapi.json');
  const raw = sourceText('integrator/openapi.json');
  if (raw === null) return { spec: null, withheld: 'not published yet' };
  const text = `${JSON.stringify(JSON.parse(raw), null, 2)}\n`;
  const hits = scanText(text, rulesFor(root, allowedInternalNames(from)));
  if (hits.length) return { spec: null, withheld: `${hits.length} leak hits (${[...new Set(hits.map((h) => h.match))].slice(0, 5).join(', ')}, …)` };
  return { spec: text, withheld: null };
}
const reference = referenceSpec();

function errorCodesPage() {
  const from = path.join(source, 'integrator', 'error-codes.json');
  const raw = sourceText('integrator/error-codes.json');
  if (raw === null) return { page: null, withheld: 'not published yet', hits: [] };
  const contract = JSON.parse(raw);
  if (typeof contract.version !== 'string' || !contract.version || !Array.isArray(contract.codes) || !contract.codes.length || !Array.isArray(contract.sourceReasons) || !contract.sourceReasons.length) {
    throw new Error(`${from}: expected version, nonempty codes and nonempty sourceReasons`);
  }
  const rules = rulesFor(root, allowedInternalNames(path.join(source, 'integrator', 'openapi.json')));
  const hits = [];
  for (const [kind, rows] of [['code', contract.codes], ['reason', contract.sourceReasons]]) {
    const seen = new Set();
    for (const row of rows) {
      if (typeof row[kind] !== 'string' || !row[kind] || seen.has(row[kind]) ||
          typeof row.meaning !== 'string' || typeof row.remedy !== 'string' || typeof row.retryable !== 'boolean' ||
          (kind === 'code' && (!Array.isArray(row.status) || row.status.some((status) => !Number.isInteger(status) || status < 400 || status > 599)))) {
        throw new Error(`${from}: invalid or duplicate ${kind} row`);
      }
      seen.add(row[kind]);
      // A leak in the row's own name cannot be withheld by naming it: refuse the page instead.
      if (scanText(row[kind], rules).length) throw new Error(`ERROR_CODE_NAME_LEAKS a ${kind} name fails the leak rules; the API must rename it`);
      for (const hit of scanText(JSON.stringify(row), rules)) hits.push({ row: row[kind], rule: hit.rule });
    }
  }
  // A row whose own text fails the leak rules is left off the public page, never rewritten here:
  // the API owns the wording. The page names what it withholds so coverage reads it as declared,
  // and --check stays red unless samples/withheld-rows.json records why that row may stay off.
  const withheldRows = [...new Set(hits.map((hit) => hit.row))].sort();
  const allowFile = path.join(root, 'samples', 'withheld-rows.json');
  const allowed = existsSync(allowFile) ? JSON.parse(readFileSync(allowFile, 'utf8')).rows ?? {} : {};
  const unexplained = withheldRows.filter((row) => typeof allowed[row] !== 'string' || !allowed[row].trim());
  const keep = (key) => (row) => !withheldRows.includes(row[key]);
  // Escape table/MDX syntax; never alter the contract's wording. Rows are omitted only when withheld above.
  const cell = (value) => String(value).replace(/&/g, '&amp;').replace(/\|/g, '&#124;')
    .replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;').replace(/\r?\n/g, '<br />');
  // Each row carries its own name as an anchor: an error body's docUrl ends in #<CODE>. A name that is
  // not a plain identifier would make a broken anchor, so it refuses the page instead.
  const anchor = (name) => {
    if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(name)) throw new Error(`ERROR_CODE_ANCHOR_INVALID ${JSON.stringify(name)}`);
    return `<span id="${name}"></span>`;
  };
  const sorted = (rows, key) => [...rows].sort((a, b) => a[key] < b[key] ? -1 : a[key] > b[key] ? 1 : 0);
  // Codes are grouped by HTTP status so a reader holding a status jumps straight to its codes.
  // A code with several statuses sits under its first; one with none is a stream event.
  const STATUS = {
    400: ['Bad request', 'The request is malformed or a value is out of range.', 'Fix the request; resending it unchanged fails again.'],
    401: ['Unauthorized', 'The credential or its signature was not accepted.', 'Check the key, token and signature.'],
    403: ['Forbidden', 'The credential lacks a permission, scope or grant.', 'Use a credential that holds it, or ask an admin to grant it.'],
    404: ['Not found', 'The resource does not exist or is not visible to this credential.', 'Check the id and the workspace.'],
    405: ['Method not allowed', 'The method is not supported on this path.', 'Use the documented method.'],
    408: ['Request timeout', 'The request took too long to arrive.', 'Retry.'],
    409: ['Conflict', 'The resource is in a state that does not allow this, or a replay does not match.', 'Read the resource, then act on its current state.'],
    410: ['Gone', 'The resource or quote no longer exists.', 'Request a new one.'],
    412: ['Precondition failed', 'The `If-Match` revision is stale.', 'Read the resource again and retry with its revision.'],
    413: ['Payload too large', 'The request body is too large.', 'Send less in one request.'],
    415: ['Unsupported media type', 'The body is not JSON.', 'Send `Content-Type: application/json`.'],
    422: ['Unprocessable', 'The request is valid but cannot be carried out as asked.', 'Change what you ask for.'],
    423: ['Locked', 'The workspace or resource is frozen.', 'An admin must lift the freeze first.'],
    428: ['Precondition required', 'A required header such as `If-Match` is missing.', 'Send the header.'],
    429: ['Too many requests', 'A rate limit or budget was reached.', 'Wait `Retry-After`, then retry.'],
    500: ['Internal error', 'TetraFi failed while handling the request.', 'Retry with the same `Idempotency-Key`; recover orders by quote.'],
    501: ['Not implemented', 'The operation is not available.', 'Do not retry.'],
    502: ['Bad gateway', 'A venue or provider failed.', 'Retry, or use another venue.'],
    503: ['Unavailable', 'A dependency is temporarily unavailable.', 'Retry after `Retry-After`; recover orders by quote.'],
    504: ['Gateway timeout', 'A venue or provider did not answer in time.', 'Recover the order by its quote before retrying.'],
  };
  const codes = contract.codes.filter(keep('code'));
  const groups = new Map();
  for (const row of sorted(codes, 'code')) {
    const status = row.status.length ? row.status[0] : 0;
    if (status && !STATUS[status]) throw new Error(`ERROR_CODE_STATUS_UNNAMED ${status}: name it in sync-contract.mjs`);
    if (!groups.has(status)) groups.set(status, []);
    groups.get(status).push(row);
  }
  const order = [...groups.keys()].sort((a, b) => (a || 1000) - (b || 1000));
  const title = (status) => status ? `${status} ${STATUS[status][0]}` : 'Stream events';
  const slug = (status) => title(status).toLowerCase().replace(/[^a-z0-9 ]/g, '').trim().replace(/\s+/g, '-');
  return { page: [
    '---',
    'title: "Error codes"',
    'description: "Every API refusal and source reason, grouped by HTTP status, with its meaning, what to do and whether to retry."',
    '---',
    '',
    '{/* Generated by scripts/sync-contract.mjs from tetrafi-rfq docs/api/integrator/error-codes.json. Edit the source, then run npm run sync. */}',
    ...(withheldRows.length ? [`{/* Withheld by the leak rules until the API changes its text: ${withheldRows.join(', ')} */}`] : []),
    '',
    'Find the code from the `error` field of the response, or jump to its HTTP status below. To parse the error body and retry safely, read [Errors and refusals](/trade/errors).',
    '',
    '<Note>New codes and reasons can appear at any time. Handle one you do not recognise by its HTTP status ([Codes you do not know](/trade/errors#codes-you-do-not-know)).</Note>',
    '',
    '## Refusal codes',
    '',
    '| Status | Codes | Usually means | What to do |',
    '| :--- | :--- | :--- | :--- |',
    ...order.map((status) => status
      ? `| [${title(status)}](#${slug(status)}) | ${groups.get(status).length} | ${STATUS[status][1]} | ${STATUS[status][2]} |`
      : `| [Stream events](#stream-events) | ${groups.get(status).length} | Sent on a stream, not as an HTTP response. | See the code. |`),
    '',
    ...order.flatMap((status) => [
      `### ${title(status)}`,
      '',
      '| Code | Meaning | What to do | Retryable |',
      '| :--- | :--- | :--- | :--- |',
      ...groups.get(status).map((row) => `| ${anchor(row.code)}\`${cell(row.code)}\`${row.status.length > 1 ? ` (also ${row.status.slice(1).join(', ')})` : ''} | ${cell(row.meaning)} | ${cell(row.remedy)} | ${row.retryable ? 'Yes' : 'No'} |`),
      '',
    ]),
    '## Source reasons',
    '',
    'A source reason says why one venue did not quote; the request as a whole still succeeded. Read the remedy before retrying.',
    '',
    '| Reason | Meaning | What to do | Retryable |',
    '| :--- | :--- | :--- | :--- |',
    ...sorted(contract.sourceReasons.filter(keep('reason')), 'reason').map((row) => `| ${anchor(row.reason)}\`${cell(row.reason)}\` | ${cell(row.meaning)} | ${cell(row.remedy)} | ${row.retryable ? 'Yes' : 'No'} |`),
    '',
  ].join('\n'), withheld: null, hits, unexplained };
}
const errorCodes = errorCodesPage();

// The webhook event catalogue lives only in the full spec, as one extension; nothing else of that spec
// is read. Only subscribable events are listed, in the catalogue's own group order. A row whose text
// fails the leak rules is withheld like an error-code row. A name that is not the dotted canonical
// form (a spec exported before the names were canonical) refuses the page, so a refused name is never
// published as one to subscribe to.
function webhookEventsPage() {
  const from = path.join(source, 'openapi.json');
  const raw = sourceText('openapi.json');
  if (raw === null) return { page: null, withheld: 'full spec not found', hits: [] };
  const catalogue = JSON.parse(raw)['x-tetrafi-webhook-event-catalogue'];
  if (!Array.isArray(catalogue?.events) || !catalogue.events.length || !Array.isArray(catalogue?.groups) || !catalogue.groups.length) {
    return { page: null, withheld: 'no x-tetrafi-webhook-event-catalogue in the full spec', hits: [] };
  }
  const events = catalogue.events.filter((row) => row.subscribable === true);
  const stale = events.filter((row) => typeof row.event !== 'string' || !/^[a-z][a-z_]*(?:\.[a-z][a-z_]*)+$/.test(row.event));
  if (stale.length) return { page: null, withheld: `event names not canonical: ${stale.slice(0, 5).map((row) => row.event).join(', ')}${stale.length > 5 ? ', …' : ''}`, hits: [] };
  const rules = rulesFor(root, allowedInternalNames(path.join(source, 'integrator', 'openapi.json')));
  const hits = [];
  for (const row of events) {
    if (typeof row.label !== 'string' || typeof row.description !== 'string' || typeof row.group !== 'string') throw new Error(`${from}: invalid webhook event row ${row.event}`);
    if (scanText(row.event, rules).length) throw new Error(`WEBHOOK_EVENT_NAME_LEAKS ${row.event}; the API must rename it`);
    for (const hit of scanText(JSON.stringify(row), rules)) hits.push({ row: row.event, rule: hit.rule });
  }
  const withheldRows = [...new Set(hits.map((hit) => hit.row))].sort();
  const allowFile = path.join(root, 'samples', 'withheld-rows.json');
  const allowed = existsSync(allowFile) ? JSON.parse(readFileSync(allowFile, 'utf8')).rows ?? {} : {};
  const unexplained = withheldRows.filter((row) => typeof allowed[row] !== 'string' || !allowed[row].trim());
  const cell = (value) => String(value).replace(/&/g, '&amp;').replace(/\|/g, '&#124;')
    .replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;').replace(/\r?\n/g, '<br />');
  const sections = [];
  for (const group of catalogue.groups) {
    const rows = events.filter((row) => row.group === group.id && !withheldRows.includes(row.event));
    if (!rows.length) continue;
    sections.push(`## ${cell(group.label)}`, '', '| Event | What it means |', '| :--- | :--- |',
      ...rows.map((row) => `| <span id="${row.event}"></span>\`${row.event}\` | ${cell(row.description)} |`), '');
  }
  const ungrouped = events.filter((row) => !catalogue.groups.some((group) => group.id === row.group));
  if (ungrouped.length) throw new Error(`${from}: events in no listed group: ${ungrouped.map((row) => row.event).join(', ')}`);
  return { page: [
    '---',
    'title: "Webhook events"',
    'description: "Every event a webhook can subscribe to, by area, with what it means."',
    '---',
    '',
    '{/* Generated by scripts/sync-contract.mjs from tetrafi-rfq docs/api/openapi.json (x-tetrafi-webhook-event-catalogue). Edit the source, then run npm run sync. */}',
    ...(withheldRows.length ? [`{/* Withheld by the leak rules until the API changes its text: ${withheldRows.join(', ')} */}`] : []),
    '',
    'Choose events when you add a webhook. Every event arrives in the same envelope, `{id, type, apiVersion, createdAt, data}`, signed with Standard Webhooks: [Webhooks](/trade/webhooks) shows how to verify and handle it. More events can be added: answer one you do not handle with a `2xx`.',
    '',
    ...sections,
  ].join('\n'), withheld: null, hits, unexplained };
}
const webhookEvents = webhookEventsPage();

// Scope and checkbox names belong to the integrator export. Until scopes are exported, publish
// only an unavailable notice, never rows that turn missing metadata into "no permission needed".
function permissionsPage() {
  if (!reference.spec) return { page: null, withheld: reference.withheld, missingLabels: [] };
  const spec = JSON.parse(reference.spec);
  const methods = new Set(['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']);
  const operations = [];
  for (const [route, item] of Object.entries(spec.paths ?? {})) {
    if (item.$ref) throw new Error(`PERMISSIONS_PATH_REFERENCE_UNRESOLVED ${route}`);
    for (const [method, operation] of Object.entries(item)) {
      if (!methods.has(method)) continue;
      const security = operation.security ?? spec.security ?? [];
      if (!Array.isArray(security) || security.some((requirement) => !requirement ||
          typeof requirement !== 'object' || Array.isArray(requirement) ||
          Object.values(requirement).some((scopes) => !Array.isArray(scopes) ||
            scopes.some((scope) => typeof scope !== 'string' || !scope.trim())))) {
        throw new Error(`PERMISSIONS_SECURITY_INVALID ${method.toUpperCase()} ${route}`);
      }
      if (operation.summary !== undefined && typeof operation.summary !== 'string') {
        throw new Error(`PERMISSIONS_SUMMARY_INVALID ${method.toUpperCase()} ${route}`);
      }
      operations.push({ route, method: method.toUpperCase(), summary: operation.summary, security });
    }
  }
  const hasScopes = operations.some(({ security }) => security.some((requirement) =>
    Object.values(requirement).some((scopes) => scopes.length)));
  const heading = [
    '---',
    'title: "Permissions"',
    'description: "API-key scopes and the app permissions that grant them, for each API operation."',
    '---',
    '',
    '{/* Generated by scripts/sync-contract.mjs from tetrafi-rfq docs/api/integrator/openapi.json. Edit the source, then run npm run sync. */}',
    '',
  ];
  if (!hasScopes) return { page: [
    ...heading,
    'The permission matrix is not yet available because the API specification has not exported operation scopes. This does not mean that operations need no permissions. See [Authentication permissions](/authentication#permissions) for the app permissions you can select.',
    '',
  ].join('\n'), withheld: null, missingLabels: [], scopesNotExported: true };

  const labels = spec.components?.securitySchemes?.api_key?.['x-tetrafi-scopes'];
  const missingLabels = new Set();
  const cell = (value) => value.replace(/&/g, '&amp;').replace(/\|/g, '&#124;')
    .replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;')
    .replace(/`/g, '&#96;').replace(/\r?\n/g, '<br />');
  // Code spans are literal in MDX: only a pipe, which would split the table cell, is escaped.
  const code = (value) => `\`${value.replace(/\|/g, '\\|')}\``;
  // The summary's first line names the operation; later rustdoc lines repeat the route. Balanced
  // backticks stay code spans; an unbalanced one is escaped so it cannot open a span across cells.
  const operationName = (summary) => {
    const line = (summary ?? '').split(/\r?\n/).find((part) => part.trim())?.trim() ?? '';
    const parts = line.split('`');
    if (parts.length % 2 === 0) return cell(line);
    return parts.map((part, i) => (i % 2 ? code(part) : cell(part))).join('');
  };
  const permission = (scope) => {
    const label = labels && Object.hasOwn(labels, scope) ? labels[scope]?.permission : undefined;
    if (typeof label === 'string' && label.trim()) return cell(label);
    missingLabels.add(scope);
    return `SCOPE_LABEL_MISSING (${cell(scope)})`;
  };
  const rows = operations.sort((a, b) => a.route < b.route ? -1 : a.route > b.route ? 1 :
    a.method < b.method ? -1 : a.method > b.method ? 1 : 0).map(({ route, method, summary, security }) => {
    const keyRequirements = security.filter((requirement) => Object.hasOwn(requirement, 'api_key'));
    let scopes;
    let permissions;
    if (keyRequirements.length) {
      scopes = keyRequirements.map(({ api_key }) => api_key.length ?
        api_key.map(code).join('<br />') : 'None').join(' or ');
      permissions = keyRequirements.map(({ api_key }) => api_key.length ?
        api_key.map(permission).join('<br />') : 'None').join(' or ');
    } else {
      scopes = !security.length || security.some((requirement) => !Object.keys(requirement).length) ?
        'No API key required' : 'Session only';
      permissions = 'Not applicable';
    }
    return `| ${method} | ${code(route)} | ${operationName(summary)} | ${scopes} | ${permissions} |`;
  });
  return { page: [
    ...heading,
    'Find the scopes an operation requires and the matching checkboxes under **Permissions** when you create an API key. The scopes and labels below come from the API specification; see [Authentication](/authentication#permissions) for how key permissions work.',
    '',
    'Scopes within one requirement are all required. Requirements separated by “or” are alternatives. **None** means the API-key operation needs no scope, not that it needs no authentication. **Session only** means the operation does not accept an API key. **No API key required** means the specification allows the operation without API-key authentication; it may still require credentials in its request.',
    '',
    ...(missingLabels.size ? ['<Warning>', 'Some scopes have no exported app permission label. Entries marked `SCOPE_LABEL_MISSING` are incomplete; do not infer a checkbox from the scope name.', '</Warning>', ''] : []),
    '| Method | Path | Operation | API-key scopes | Permission in the app |',
    '| :--- | :--- | :--- | :--- | :--- |',
    ...rows,
    '',
  ].join('\n'), withheld: null, missingLabels: [...missingLabels].sort() };
}
const permissions = permissionsPage();

const outputs = [['compatibility.mdx', compatibilityPage()]];
if (reference.spec) outputs.push([path.join('api-reference', 'openapi.json'), reference.spec]);
if (errorCodes.page) outputs.push([path.join('reference', 'error-codes.mdx'), errorCodes.page]);
if (webhookEvents.page) outputs.push([path.join('reference', 'webhook-events.mdx'), webhookEvents.page]);
if (permissions.page) outputs.push([path.join('reference', 'permissions.mdx'), permissions.page]);

const staleReference = !reference.spec && existsSync(path.join(root, 'api-reference', 'openapi.json'));
const staleErrorCodes = !errorCodes.page && existsSync(path.join(root, 'reference', 'error-codes.mdx'));
const staleWebhookEvents = !webhookEvents.page && existsSync(path.join(root, 'reference', 'webhook-events.mdx'));
const stalePermissions = !permissions.page && existsSync(path.join(root, 'reference', 'permissions.mdx'));
function reportWithheld() {
  if (reference.withheld) console.log(`REFERENCE_WITHHELD ${reference.withheld}`);
  if (errorCodes.withheld) console.log(`ERROR_CODES_WITHHELD ${errorCodes.withheld}`);
  for (const hit of errorCodes.hits) console.log(`ERROR_CODE_ROW_WITHHELD ${hit.row} ${hit.rule}`);
  for (const row of errorCodes.unexplained ?? []) console.log(`ERROR_CODE_ROW_UNEXPLAINED ${row} (record why in samples/withheld-rows.json, or fix the API text)`);
  if (webhookEvents.withheld) console.log(`WEBHOOK_EVENTS_WITHHELD ${webhookEvents.withheld}`);
  for (const hit of webhookEvents.hits) console.log(`WEBHOOK_EVENT_ROW_WITHHELD ${hit.row} ${hit.rule}`);
  for (const row of webhookEvents.unexplained ?? []) console.log(`WEBHOOK_EVENT_ROW_UNEXPLAINED ${row} (record why in samples/withheld-rows.json, or fix the API text)`);
  if (permissions.withheld) console.log(`PERMISSIONS_WITHHELD ${permissions.withheld}`);
  if (permissions.scopesNotExported) console.log('SCOPES_NOT_EXPORTED permission matrix is not yet available');
  for (const scope of permissions.missingLabels) console.log(`SCOPE_LABEL_MISSING ${scope}`);
}
const drift = outputs.filter(([file, content]) => !existsSync(path.join(root, file)) || readFileSync(path.join(root, file), 'utf8') !== content);
