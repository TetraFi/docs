// docs.json keeps its hand-written navigation; only the API reference tab's endpoint groups are generated.
function docsJson() {
  if (!endpoints.nav) return null;
  const doc = JSON.parse(readFileSync(path.join(root, 'docs.json'), 'utf8'));
  const tab = doc.navigation?.tabs?.find((t) => t.tab === 'API reference');
  if (!tab) throw new Error('DOCS_JSON_API_REFERENCE_TAB_MISSING');
  // Endpoint groups are the ones whose pages are all generated operation stubs.
  const generated = (g) => g.openapi || (g.pages?.length && g.pages.every((p) => typeof p === 'string' && p.startsWith('api-reference/')));
  const first = tab.groups.findIndex(generated);
  if (first < 0) throw new Error('DOCS_JSON_ENDPOINT_GROUPS_MISSING');
  const kept = tab.groups.filter((g) => !generated(g));
  kept.splice(first, 0, ...endpoints.nav);
  tab.groups = kept;
  return `${JSON.stringify(doc, null, 2)}\n`;
}

// The asset classes a page names come from the spec's AssetKind, the `kind` of every
// GET /api/v1/assets entry, so the site never lists a class the API does not return.
function assetKindsSnippet() {
  if (!reference.spec) return null;
  const schemas = JSON.parse(reference.spec).components?.schemas ?? {};
  // A spec without the assets entry schema publishes no asset list to describe.
  if (!schemas.AssetEntry) return null;
  const kinds = listedValues(schemas.AssetKind);
  if (!Array.isArray(kinds) || !kinds.length || kinds.some((kind) => typeof kind !== 'string')) throw new Error('ASSET_KIND_ENUM_MISSING');
  const kindRef = schemas.AssetEntry?.properties?.kind;
  const refs = [kindRef?.$ref, ...(kindRef?.allOf ?? []).map((part) => part.$ref)];
  if (!refs.includes('#/components/schemas/AssetKind')) throw new Error('ASSET_ENTRY_KIND_NOT_ASSET_KIND');
  const list = kinds.map((kind) => `\`${kind}\``);
  return [
    '{/* Generated by scripts/sync-contract.mjs from tetrafi-rfq docs/api/integrator/openapi.json (AssetKind). Edit the source, then run npm run sync. */}',
    '',
    `Every asset \`GET /api/v1/assets\` lists carries a \`kind\`: ${list.slice(0, -1).join(', ')} or ${list.at(-1)}. The list can grow: treat a value you do not know as other ([Conventions](/reference/conventions#values)).`,
    '',
  ].join('\n');
}

