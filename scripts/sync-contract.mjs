function endpointMap() {
  if (!permissions.operations) return { page: null, nav: null };
  const ops = permissions.operations;
  checkEndpointNames(ops);
  checkJourneys(ops.map((op) => `${op.method} ${op.route}`));
  for (const tag of new Set(ops.map((op) => op.tag))) {
    if (!ENDPOINT_GROUPS.some(({ tags }) => tags.includes(tag))) throw new Error(`SPEC_TAG_UNGROUPED ${tag}`);
  }
  const verbs = { GET: 0, POST: 1, PATCH: 2, PUT: 3, DELETE: 4 };
  const order = (a, b) => a.route < b.route ? -1 : a.route > b.route ? 1 : verbs[a.method] - verbs[b.method];
  const groups = ENDPOINT_GROUPS.map((g) => ({ ...g, ops: g.tags.flatMap((tag) => ops.filter((op) => op.tag === tag).sort(order)) }))
    .filter((g) => g.ops.length);
  // One stub page per operation, so the sidebar, the links below and `mint broken-links` all see a
  // real page; Mintlify renders it from the spec.
  const stubPath = (op) => `api-reference/${pageSlug(op.tag)}/${pageSlug(endpointName(op.method, op.route))}`;
  // Each stub links the guide that walks through its operation, named by that guide's own title.
  // A guide with an #anchor is named by that heading, so the link text says where it lands.
  const guideTitle = (guide) => {
    const [page, anchor] = guide.split('#');
    const file = path.join(root, `${page.replace(/^\//, '')}.mdx`);
    const text = existsSync(file) ? readFileSync(file, 'utf8') : '';
    const heading = anchor && [...text.matchAll(/^#{2,4} (.+)$/gm)].map((m) => m[1].trim())
      .find((h) => h.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/\s+/g, '-') === anchor);
    const title = anchor ? heading : (text.match(/^title:\s*"([^"]+)"/m) ?? [])[1];
    if (!title) throw new Error(`ENDPOINT_GUIDE_MISSING ${guide}`);
    return title;
  };
  const guideFor = (op) => ENDPOINT_GUIDES[`${op.method} ${op.route}`] ?? ENDPOINT_GROUPS.find(({ tags }) => tags.includes(op.tag)).guide;
  // Each stub: one fits line (journey step, permission, walkthrough), then the operation's hand-written
  // notes (snippets/endpoints/<tag>/<name>.mdx: rules table and closed toggles) when it has them.
  const snippetPath = (op) => `snippets/endpoints/${pageSlug(op.tag)}/${pageSlug(endpointName(op.method, op.route))}.mdx`;
  const needs = (op) => {
    const { scopes, permissions: labels } = permissions.access(op);
    // "None" means no extra permission, never no credential: the call still needs a valid key or token.
    if (labels === 'None') return 'Any valid API key or token';
    if (labels !== 'Not applicable') return `Needs ${labels.replace(/<br \/>/g, ' and ')}`;
    if (scopes === 'Session only') return 'Signed-in members only';
    // The token exchange authenticates with the service account's own credentials in the body.
    return op.route === '/api/v1/oauth/token' ? "Your service account's client id and secret" : 'No API key needed';
  };
  const stubs = ops.map((op) => {
    const key = `${op.method} ${op.route}`;
    const notes = existsSync(path.join(root, snippetPath(op)));
    const line = fitsLine(key, needs(op), `Walkthrough: [${guideTitle(guideFor(op))}](${guideFor(op)})`);
    return [`${stubPath(op)}.mdx`, ['---', `title: "${endpointName(op.method, op.route)}"`, `openapi: "api-reference/openapi.json ${op.method} ${op.route}"`, '---', '',
      ...(notes ? [`import Notes from '/${snippetPath(op)}'`, ''] : []),
      line, ...(notes ? ['', '<Notes />'] : []), ''].join('\n')];
  });
  const seen = new Set();
  for (const [file] of stubs) {
    if (seen.has(file)) throw new Error(`ENDPOINT_PAGE_DUPLICATE ${file}`);
    seen.add(file);
  }
  // A group's hand-written intro (api-reference/intros/<group>.mdx) leads its sidebar group.
  const intro = (group) => `api-reference/intros/${pageSlug(group)}`;
  const nav = groups.map(({ group, ops: list }) => ({ group, pages: [...(existsSync(path.join(root, `${intro(group)}.mdx`)) ? [intro(group)] : []), ...list.map(stubPath)] }));
  const page = [
    '---',
    'title: "Endpoints at a glance"',
    `description: "All ${ops.length} API operations by task, with the scopes each needs and the guide that walks through it."`,
    '---',
    '',
    '{/* Generated by scripts/sync-contract.mjs from tetrafi-rfq docs/api/integrator/openapi.json. Edit the source, then run npm run sync. */}',
    '',
    // A skimmable index: one jump row per group (its purpose said once), then one row per call. Each group
    // heading links its intro (how the calls fit together) and the guide that walks through them.
    `Every call, one row each, grouped like the sidebar. Paths are relative to the [base URL](/reference/conventions#requests); \`…\` stands for \`${WORKSPACE_PREFIX}\`. A call's page has its parameters, responses and a request you can try; [Permissions](/reference/permissions) explains the scopes. First trade? Start with the [Quickstart](/quickstart).`,
    '',
    '| Group | Calls | What for |',
    '| :--- | :--- | :--- |',
    ...groups.map(({ group, purpose, ops: list }) => `| [${group}](#${pageSlug(group)}) | ${list.length} | ${purpose} |`),
    '',
    ...groups.flatMap(({ group, guide, ops: list }) => [
      `## ${group}`,
      '',
      [...(existsSync(path.join(root, `${intro(group)}.mdx`)) ? [`[How these calls fit](/${intro(group)})`] : []), `Walkthrough: [${guideTitle(guide)}](${guide})`].join(' · '),
      '',
      '| Endpoint | Method and path | API-key scopes |',
      '| :--- | :--- | :--- |',
      ...list.map((op) => {
        const guideLink = ENDPOINT_GUIDES[`${op.method} ${op.route}`];
        const name = `[${endpointName(op.method, op.route)}](/${stubPath(op)})` + (guideLink ? ` · [guide](${guideLink})` : '');
        const shown = op.route.replace(WORKSPACE_PREFIX, '…');
        return `| ${name} | ${op.method} ${permissions.code(shown)} | ${permissions.access(op).scopes} |`;
      }),
      '',
    ]),
  ].join('\n');
  return { page, nav, stubs };
}
