const staleReference = !reference.spec && existsSync(path.join(root, 'api-reference', 'openapi.json'));
const staleErrorCodes = !errorCodes.page && existsSync(path.join(root, 'reference', 'error-codes.mdx'));
const staleWebhookEvents = !webhookEvents.page && existsSync(path.join(root, 'reference', 'webhook-events.mdx'));
const stalePermissions = !permissions.page && existsSync(path.join(root, 'reference', 'permissions.mdx'));
function reportWithheld() {
  if (reference.withheld) console.log(`REFERENCE_WITHHELD ${reference.withheld}`);
  if (errorCodes.withheld) console.log(`ERROR_CODES_WITHHELD ${errorCodes.withheld}`);
  for (const hit of errorCodes.hits) console.log(`ERROR_CODE_ROW_WITHHELD ${hit.row} ${hit.rule}`);
  for (const row of errorCodes.unexplained ?? []) console.log(`ERROR_CODE_ROW_UNEXPLAINED ${row} (record why in samples/withheld-rows.json, or fix the API text)`);
  if (webhookEvents.withheld) console.log(`WEBHOOK_EVENTS_WITHHELD ${webhookEvents.withheld}`);
  for (const hit of webhookEvents.hits) console.log(`WEBHOOK_EVENT_ROW_WITHHELD ${hit.row} ${hit.rule}`);
  for (const row of webhookEvents.unexplained ?? []) console.log(`WEBHOOK_EVENT_ROW_UNEXPLAINED ${row} (record why in samples/withheld-rows.json, or fix the API text)`);
  if (permissions.withheld) console.log(`PERMISSIONS_WITHHELD ${permissions.withheld}`);
  if (permissions.scopesNotExported) console.log('SCOPES_NOT_EXPORTED permission matrix is not yet available');
  for (const scope of permissions.missingLabels) console.log(`SCOPE_LABEL_MISSING ${scope}`);
}
// --only <file> (repeatable) writes or checks just the named outputs and leaves every other generated
// file alone, so one page can be regenerated while the rest wait for a newer contract export. A name
// that is not an output of this run (a typo, or a page withheld) refuses the run rather than doing nothing.
export function onlyOutputs(argv, files) {
  const named = argv.flatMap((arg, i) => (arg === '--only' ? [argv[i + 1]] : arg.startsWith('--only=') ? [arg.slice(7)] : []));
  if (!named.length) return null;
  const known = new Set(files);
  const wanted = new Set();
  for (const name of named) {
    if (!name || name.startsWith('--')) throw new Error('SYNC_ONLY_VALUE_MISSING --only needs an output file, e.g. --only reference/error-codes.mdx');
    const file = path.normalize(name).replace(/^\.\//, '');
    if (!known.has(file)) throw new Error(`SYNC_ONLY_UNKNOWN_OUTPUT ${name} is not an output of this run (outputs include ${[...known].filter((f) => !f.startsWith('api-reference/')).join(', ')})`);
    wanted.add(file);
  }
  return wanted;
}
const only = onlyOutputs(process.argv.slice(2), outputs.map(([file]) => file));
const drift = outputs.filter(([file, content]) => !existsSync(path.join(root, file)) || readFileSync(path.join(root, file), 'utf8') !== content);
if (only) {
  const selected = outputs.filter(([file]) => only.has(file));
  const unexplained = only.has(path.join('reference', 'error-codes.mdx')) ? errorCodes.unexplained ?? [] : [];
  for (const row of unexplained) console.log(`ERROR_CODE_ROW_UNEXPLAINED ${row} (record why in samples/withheld-rows.json, or fix the API text)`);
  if (check) {
    const drifted = drift.filter(([file]) => only.has(file));
    for (const [file] of drifted) console.log(`CONTRACT_DRIFT ${file}`);
    console.log(`sync-contract --check --only: ${selected.length} files, ${drifted.length} drifted`);
    process.exit(drifted.length || unexplained.length ? 1 : 0);
  }
  for (const [file, content] of selected) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    writeFileSync(path.join(root, file), content);
  }
  console.log(`sync-contract --only: wrote ${selected.length} files`);
  process.exit(unexplained.length ? 1 : 0);
}
if (check) {
  for (const [file] of drift) console.log(`CONTRACT_DRIFT ${file}`);
  if (staleReference) console.log('CONTRACT_DRIFT api-reference/openapi.json (present while the reference is withheld)');
  if (staleErrorCodes) console.log('CONTRACT_DRIFT reference/error-codes.mdx (present while the error codes are withheld)');
  if (staleWebhookEvents) console.log('CONTRACT_DRIFT reference/webhook-events.mdx (present while the webhook events are withheld)');
  if (stalePermissions) console.log('CONTRACT_DRIFT reference/permissions.mdx (present while the permissions are withheld)');
  for (const file of staleEndpointPages) console.log(`CONTRACT_DRIFT ${file} (no current operation has this page: renamed or removed; archive it)`);
  reportWithheld();
  console.log(`sync-contract --check: ${outputs.length} files, ${drift.length} drifted`);
  process.exit(drift.length || staleEndpointPages.length || staleReference || errorCodes.withheld || staleErrorCodes || errorCodes.unexplained?.length || staleWebhookEvents || webhookEvents.unexplained?.length || stalePermissions || permissions.missingLabels.length ? 1 : 0);
}
for (const [file, content] of outputs) {
  mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
  writeFileSync(path.join(root, file), content);
}
reportWithheld();
if (staleReference) {
  console.log('api-reference/openapi.json is present while the reference is withheld; archive it: mv api-reference/openapi.json .archive/api-reference/');
  process.exitCode = 1;
}
if (staleErrorCodes) console.log('reference/error-codes.mdx is present while the error codes are withheld; archive it before publishing.');
if (errorCodes.withheld || staleErrorCodes) process.exitCode = 1;
if (stalePermissions) {
  console.log('reference/permissions.mdx is present while the permissions are withheld; archive it before publishing.');
  process.exitCode = 1;
}
for (const file of staleEndpointPages) {
  console.log(`${file} is not a current operation page (renamed or removed); archive it.`);
  process.exitCode = 1;
}
console.log(`sync-contract: wrote ${outputs.length} files`);
